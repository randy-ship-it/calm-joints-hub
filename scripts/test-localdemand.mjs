// Offline checks for the vendored Calm Joints local-demand page.
// The browser check that calls the live estimator is scripts/test-localdemand-browser.mjs.
import assert from 'assert';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { ANCHORS, applyFinePrint, assertClean, stripRoyaltyOffer, transform } from './sync-localdemand.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const page = fs.readFileSync(path.join(root, 'localdemand/index.html'), 'utf8');

assertClean(page);
assert.ok(page.startsWith('<!-- Generated by scripts/sync-localdemand.mjs'));
assert.ok(!page.includes('labeldrawMap'), 'ad-value removal must not splice drawMap onto the label');
const NEW_FINE = 'Estimates only, not a guarantee. You may see more or less activity in your area. We are learning how brand audience views convert to bookings in real time, and we update these numbers as the data gets more accurate.';
const OLD_FINE = 'Estimates based on current network traffic and typical health-media CPMs; actual results vary.';
assert.ok(page.includes(NEW_FINE));
assert.ok(!page.includes(OLD_FINE));
assert.ok(!/\bCPM\b/.test(page));
assert.strictEqual(applyFinePrint(`<p class="fine">${OLD_FINE}</p>`), `<p class="fine">${NEW_FINE}</p>`);
assert.strictEqual(applyFinePrint(`<p class="fine">${NEW_FINE}</p>`), `<p class="fine">${NEW_FINE}</p>`);
assert.strictEqual(applyFinePrint(`<p class="fine">${OLD_FINE}</p><p class="fine">${NEW_FINE}</p>`), `<p class="fine">${NEW_FINE}</p>`);
assert.throws(() => applyFinePrint('<p class="fine">Something else.</p>'), /fine print missing/);
assert.throws(() => transform(page), /missing anchor/, 'sync must fail loudly if upstream anchors are already gone');
assert.throws(() => transform('<html><title>nope</title></html>'), /missing anchor|too short/);

for (const gone of ['Fall50', 'id="ofb"', '50% royalty', 'name="monetize"', 'clinichubs-fall50']) {
  assert.ok(!ANCHORS.includes(gone), gone + ' is Align-only and must not be a required anchor');
}
const reinjected = page.replace(
  '</header>',
  '</header><div class="ofr" id="ofr"><button type="button" class="ofb" id="ofb">Activate your customers: earn 50% royalty (usually 30%)</button><div class="ofp" id="ofp"><p>Code <b>Fall50</b></p><a href="https://www.scalehealth.ca/localdemand/clinichubs-fall50?code=Fall50">Launch my hub (50% payout, code Fall50)</a><form id="off"><button>Claim 50% offer</button></form></div></div><label class="mck"><input type="checkbox" name="monetize" checked><span>I also want to monetize with my own Scale hub (code Fall50)</span></label><script>var CH="https://www.scalehealth.ca/localdemand/clinichubs-fall50?code=Fall50";</script>',
);
const stripped = stripRoyaltyOffer(reinjected);
assertClean(stripped);
assert.ok(!/fall50|royalt|monetize|clinichubs/i.test(stripped));

const home = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const partners = fs.readFileSync(path.join(root, 'partners.html'), 'utf8');
assert.ok(home.includes('href="/localdemand"') && home.includes('Check local demand near you'));
assert.ok(partners.includes('href="/localdemand"') && partners.includes('Check local demand near you'));
assert.ok(partners.includes("q.get('source') !== 'localdemand'"));
assert.ok(partners.includes("type.value = 'health'"));

const vercel = JSON.parse(fs.readFileSync(path.join(root, 'vercel.json'), 'utf8'));
const rewrite = vercel.rewrites.find((r) => r.source === '/localdemand/api/estimate');
assert.ok(rewrite, 'missing estimate rewrite');
assert.strictEqual(rewrite.destination, 'https://scale-partner-dash.vercel.app/localdemand/api/estimate');
assert.ok(!JSON.stringify(vercel).includes('scale-partner-dash.vercel.app/localdemand/api/lead'));
assert.ok(!JSON.stringify(vercel).includes('api/snapshot'));

const alias = fs.readFileSync(path.join(root, 'lib/partner-alias.js'), 'utf8');
const mid = fs.readFileSync(path.join(root, 'middleware.js'), 'utf8');
assert.ok(alias.includes("'localdemand'"));
assert.ok(mid.includes('localdemand$'));

const dev = fs.readFileSync(path.join(root, 'scripts/dev-server.js'), 'utf8');
assert.ok(dev.includes("pathname === '/localdemand/api/estimate'"));
assert.ok(dev.includes('scale-partner-dash.vercel.app/localdemand/api/estimate'));

console.log('localdemand: page, links, and rewrite checks passed');
